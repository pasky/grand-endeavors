"""Round-up Quick Reference, generated from the period's frozen bulletin
snapshots (<period-dir>/snapshot/<section>.json), not from bulletin prose:
per covered endeavor the KPI headline values, the KPI assessment and the
milestone statuses as of the cutoff.

Usage:
    uv run views/quickref.py <period-dir>              print the block
    uv run views/quickref.py <period-dir> --insert F   put it into F (the round-up README)

The block is delimited by QR_START / QR_END markers. --insert replaces an
existing block, else a '<!-- quick-reference -->' placeholder line, else it
is appended. validate.py --roundup traces the block's numbers to the snapshots.
"""
import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "core"))
import ledger  # noqa: E402

QR_START = "<!-- quick-reference: generated by views/quickref.py from the snapshots; do not edit -->"
QR_END = "<!-- /quick-reference -->"
PLACEHOLDER = "<!-- quick-reference -->"
EMOJI = {"green": "🟢", "yellow": "🟡", "red": "🔴", "achieved": "✅", "unknown": "⚪"}
LEGEND = ("**Status legend** (gather/RUBRIC.md): KPI = pace versus what the goal needs, not the level; "
          "milestone = ETA on evidence. 🟢 on track or ahead · 🟡 progressing, behind pace · "
          "🔴 off track, stalled or distant · ✅ achieved · ⚪ unassessed")


def snapshots(period_dir: str) -> list[dict]:
    """The period's snapshots that have a bulletin, in framework order."""
    out = []
    for sec in ledger.SECTIONS:
        p = os.path.join(period_dir, "snapshot", f"{sec}.json")
        if os.path.exists(p) and os.path.exists(os.path.join(period_dir, f"{sec}.md")):
            with open(p, encoding="utf-8") as f:
                out.append(json.load(f))
    return out


def cell(s: str) -> str:
    return re.sub(r"\s+", " ", str(s)).replace("|", "\\|").strip()


def endeavor(section: str, fw: dict) -> tuple[str, str]:
    try:
        s, g = ledger.fw_section(section, fw)
    except KeyError:
        return section, ""
    return (f"{g['title']}: {s['title']}" if g else s["title"]), s.get("kpi", "")


def block(period_dir: str) -> str:
    fwp = os.path.join(period_dir, "framework.yaml")  # the period's framework, once frozen
    fw = ledger.framework(period_dir) if os.path.exists(fwp) else ledger.framework()
    snaps = snapshots(period_dir)
    if not snaps:
        raise ValueError(f"{period_dir}: no snapshot with a bulletin")
    period = snaps[0]["period"]
    rows = [f"## Quick Reference\n\n*As of the {period} cutoff ({snaps[0]['cutoff']}), from the ledger snapshots. "
            "Every milestone, its evidence and the KPI series: [the dashboard as of the cutoff](index.html).*\n",
            "| Endeavor | KPI | Latest value | KPI status | Milestones |",
            "|----------|-----|--------------|------------|------------|"]
    for snap in snaps:
        name, kpi_name = endeavor(snap["section"], fw)
        values = "; ".join(f"{k['current']['value']} {k['unit']} ({k['current']['obs']})" if k["current"]
                           else f"no reading ({k['metric']})" for k in snap["kpi_headlines"]) or "—"
        ass = {t: a["current"] for t, a in snap["assessments"].items()}
        k = ass.get("kpi")
        kstatus = f"{EMOJI.get(k['status'], '')} {k['label']}" if k else "not yet assessed"
        mcell = " · ".join(f"{EMOJI.get(ass[f['topic']]['status'], '')} {f['name']}" if f["topic"] in ass
                           else f"{f['name']} (not yet assessed)"
                           for f in snap.get("framework", []) if f["topic"].startswith("milestone:"))
        rows.append("| " + " | ".join(cell(x) for x in (name, kpi_name, values, kstatus, mcell or "—")) + " |")
    return "\n".join([QR_START, *rows, "", LEGEND, QR_END]) + "\n"


def insert(text: str, qr: str) -> str:
    if QR_START in text and QR_END in text:
        a, rest = text.split(QR_START, 1)
        return a + qr.rstrip("\n") + rest.split(QR_END, 1)[1]
    lines = text.splitlines(keepends=True)
    for i, ln in enumerate(lines):
        if ln.strip() == PLACEHOLDER:
            lines[i] = qr
            return "".join(lines)
    return text.rstrip("\n") + "\n\n" + qr


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("period_dir")
    ap.add_argument("--insert", metavar="FILE", help="write the block into FILE (the round-up README)")
    a = ap.parse_args()
    try:
        qr = block(a.period_dir.rstrip("/"))
    except ValueError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 1
    if not a.insert:
        sys.stdout.write(qr)
        return 0
    with open(a.insert, encoding="utf-8") as f:
        text = f.read()
    with open(a.insert, "w", encoding="utf-8") as f:
        f.write(insert(text, qr))
    print(f"quick reference -> {a.insert}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
